import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';

test('CMS migration preserves content; drafts, reuse, replacement, layout and RLS stay consistent', async () => {
 const db = new PGlite();
 try {
  await db.exec(`create role anon; create role authenticated; create schema auth; create schema storage;
   create table auth.users(id uuid primary key);
   create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
   grant usage on schema auth,storage to authenticated,anon;
   create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
   create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text,name text,metadata jsonb,created_at timestamptz default now());
   alter table storage.objects enable row level security;
   grant select,insert,update,delete on storage.objects to authenticated; grant select on storage.objects to anon;`);
  const migrations = readdirSync('database/supabase/migrations').sort();
  for(const file of migrations.filter(f=>!f.endsWith('_cms_workspace.sql'))) await db.exec(readFileSync(`database/supabase/migrations/${file}`,'utf8'));
  await db.exec(`insert into auth.users values ('00000000-0000-4000-8000-000000000001');
   insert into public.profiles(id,role) values('00000000-0000-4000-8000-000000000001','admin');
   insert into storage.objects(bucket_id,name,metadata) values('portfolio-media','existing/portrait.png','{"size":100,"mimetype":"image/png"}');
   update public.homepage_content set editorial_one_path='existing/portrait.png',editorial_one_alt='Existing portrait' where id=1;
   insert into public.capabilities(title,kind) values('Existing capability','capability');`);
  const before = (await db.query('select * from public.homepage_content')).rows;
  await db.exec(readFileSync('database/supabase/migrations/20261018134801_cms_workspace.sql','utf8'));
  assert.deepEqual((await db.query('select * from public.homepage_content')).rows,before);
  assert.equal((await db.query('select * from public.capabilities')).rows.length,1);
  assert.equal((await db.query('select * from public.media_assets')).rows.length,1);
  await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub','00000000-0000-4000-8000-000000000001',false)`);
  const id='00000000-0000-4000-8000-000000000002';
  const draft={title:'Draft fixture',slug:'draft-fixture',short_description:'',role:'',tools:[],year:null,project_type:'Personal Project',status:'Concept',section_one_heading:'',section_one_body:'',section_two_heading:'',section_two_body:'',gallery_layout:'landscape',live_url:'',repository_url:'',figma_url:'',sort_order:0};
  await db.query('select public.save_editorial_project($1,$2::jsonb)',[id,JSON.stringify(draft)]);
  await db.query('select public.save_editorial_project($1,$2::jsonb)',[id,JSON.stringify(draft)]);
  assert.equal((await db.query('select * from public.projects')).rows.length,1,'same draft ID cannot create duplicates');
  await assert.rejects(db.query('update public.projects set is_published=true where id=$1',[id]));
  const asset=(await db.query('select id from public.media_assets limit 1')).rows[0].id;
  await db.query("select public.assign_library_image($1,'cover',$2,null,'Cover alt','')",[asset,id]);
  for(let i=0;i<6;i++) await db.query("select public.assign_library_image($1,'gallery',$2,$3,$4,'')",[asset,id,i,`Landscape ${i+1}`]);
  await assert.rejects(db.query('select public.begin_media_delete($1)',[asset]),/in use/);
  const complete={...draft,short_description:'Subtitle',role:'Designer',year:2026,section_one_heading:'Idea',section_one_body:'Idea body',section_two_heading:'Build',section_two_body:'Build body'};
  await db.query('select public.save_editorial_project($1,$2::jsonb)',[id,JSON.stringify(complete)]);
  await db.query('update public.projects set is_published=true where id=$1',[id]);
  await assert.rejects(db.query('select public.save_editorial_project($1,$2::jsonb)',[id,JSON.stringify({...complete,role:''})]));
  await db.exec('set role anon');
  assert.equal((await db.query('select * from public.projects')).rows.length,1);
  await assert.rejects(db.query('select * from public.media_assets'),/permission denied/);
  await assert.rejects(db.query('select public.begin_media_delete($1)',[asset]),/permission denied/);
  await db.exec('set role authenticated');
  await db.query('update public.projects set is_published=false where id=$1',[id]);
  await db.query('select public.save_editorial_project($1,$2::jsonb)',[id,JSON.stringify({...complete,gallery_layout:'mixed'})]);
  const retained=(await db.query('select slot from public.project_media where project_id=$1',[id])).rows;
  assert.equal(retained.length,6); assert.deepEqual(retained.filter(m=>m.slot!==null).map(m=>m.slot).sort(),[3,4]);
  for(let i=0;i<3;i++) await db.query("select public.assign_library_image($1,'gallery',$2,$3,$4,'')",[asset,id,i,`Portrait ${i+1}`]);
  await db.query('update public.projects set is_published=true where id=$1',[id]);
  const next=(await db.query("insert into public.media_assets(storage_path,filename,content_type,byte_size) values('replacement.png','replacement.png','image/png',200) returning id")).rows[0].id;
  await db.query('select public.replace_library_image($1,$2)',[asset,next]);
  assert.equal((await db.query('select cover_image_url from public.projects where id=$1',[id])).rows[0].cover_image_url,'replacement.png');
  assert.equal((await db.query('select editorial_one_path from public.homepage_content')).rows[0].editorial_one_path,'replacement.png');
  assert.equal((await db.query('select * from public.media_assets')).rows.length,2,'replacement retains old file');
  await db.query('select public.begin_media_delete($1)',[asset]);
  await assert.rejects(db.query("select public.assign_library_image($1,'homepage-two',null,null,'Alt','')",[asset]),/unavailable/);
  await db.exec("select set_config('request.jwt.claim.sub','00000000-0000-4000-8000-000000000099',false)");
  assert.equal((await db.query('select * from public.media_assets')).rows.length,0);
  await assert.rejects(db.query("select public.assign_library_image($1,'homepage-two',null,null,'Alt','')",[next]),/Admin access required/);
 } finally { await db.close(); }
});
