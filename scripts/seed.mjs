import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const source = new URL("../lib/cms/seed-data.json", import.meta.url);
const destination = new URL("../supabase/seed.sql", import.meta.url);
const seed = JSON.parse(await readFile(source, "utf8"));

function sqlValue(value) {
  if (value === null) return "null";
  if (typeof value === "boolean" || typeof value === "number") return String(value);
  if (Array.isArray(value)) return `array[${value.map(sqlValue).join(", ")}]::text[]`;
  return `'${String(value).replaceAll("'", "''")}'`;
}

function insert(table, rows) {
  if (!rows.length) return "";
  const columns = Object.keys(rows[0]);
  const values = rows.map((row) => `  (${columns.map((column) => sqlValue(row[column])).join(", ")})`).join(",\n");
  // A re-run adds missing seed records, preserving edits made in the CMS.
  return `insert into public.${table} (${columns.join(", ")})\nvalues\n${values}\non conflict (id) do nothing;\n`;
}

const sql = [
  "-- Generated by node scripts/seed.mjs from lib/cms/seed-data.json.",
  "-- Do not edit this file directly. Re-running preserves existing CMS records.",
  "begin;",
  insert("site_settings", [seed.site_settings]),
  ...["projects", "project_sections", "project_media", "capabilities"].map((table) => insert(table, seed[table])),
  "commit;",
  "",
].join("\n\n");

if (process.argv.includes("--check")) {
  const current = await readFile(destination, "utf8");
  if (current !== sql) {
    throw new Error("supabase/seed.sql differs from the canonical seed. Run node scripts/seed.mjs.");
  }
  console.log("Seed SQL matches the canonical CMS data.");
} else {
  await writeFile(destination, sql, "utf8");
  console.log(`Generated ${fileURLToPath(destination)} from the canonical CMS data.`);
}
